import assert from 'node:assert/strict';
import { moduleURL } from './load-typescript.mjs';
const { analyzeProgress, getWorkoutExerciseProgress } = await import(moduleURL('src/lib/gym/progress/calculate.ts'));
const { formatWorkoutAIExport } = await import(moduleURL('src/utils/formatWorkoutAIExport.ts'));
const exercise = { id: 'squat', name: 'Goblet Squat', trackingType: 'weight_reps', dumbbellCount: 1 };
const plan = { id: 'A', name: 'Plan A', exerciseIds: [{ exerciseId: 'squat', targetSets: 3, targetRepMin: 8, targetRepMax: 12 }] };
function workout(day, reps, extras = {}) {
  const id = `workout-${day}`, startedAt = `2026-09-${String(day).padStart(2, '0')}T08:00:00Z`;
  return { id, planId:'A', startedAt, endedAt:startedAt, status:'completed',
    exercises:[{id, exerciseId:'squat',nameSnapshot:'Goblet Squat',trackingTypeSnapshot:'weight_reps',plannedSetsSnapshot:3,targetRepMin:8,targetRepMax:12,status:'completed',dumbbellCountSnapshot:1}],
    sets:reps.map((rep,i)=>({id:`${id}-${i}`,workoutExerciseId:id,setNumber:i+1,weight:10,reps:rep,completedAt:startedAt})), ...extras };
}
const data = sessions => ({ exercises:[exercise], plans:[plan], routines:[], sessions });
const analyze = input => analyzeProgress(input,'2026-09-20');
const one = input => analyze(input).exercises[0];
let input = data([workout(18,[10,9,8]),workout(19,[10,9,9])]);
assert.equal(one(input).workComparison.change,1,'A later-set improvement counts even when best set is unchanged');
assert.equal(analyze(input).workoutFeedback.improved,1);
assert.match(analyze(input).workoutFeedback.items[0].label,/\+1 total reps across 3 sets/);
assert.equal(one(input).prHistory.some(r=>r.type==='reps'),false,'No invented best-set PR');
assert.equal(one(input).sessionsWithoutImprovement,0);
assert.deepEqual(one(input).nextTarget.setTargets.map(s=>s.reps),[10,9,10]);
assert.equal(one(input).nextTarget.weight,10,'Single-dumbbell inventory supports Goblet Squat at 10kg');
assert.ok(one(input).availableLoads.includes(10),'Exported per-exercise equipment must agree with its prescription');
input=data([workout(18,[10,10,10]),workout(19,[11,8,8])]);
assert.equal(one(input).workComparison.change,-3);
assert.equal(analyze(input).workoutFeedback.improved,0,'A best-set PR cannot hide a decline in total comparable work');
assert.ok(one(input).prHistory.some(r=>r.type==='reps'));
input=data([workout(18,[10,10,10]),workout(19,[10,10,10,10])]);
assert.equal(one(input).workComparison,null,'More sets are not comparable total work');
assert.equal(analyze(input).workoutFeedback.improved,0);
assert.ok(one(input).prHistory.some(r=>r.type==='volume'));
input=data([workout(18,[12,12,12]),workout(19,[2,2,2])]);
input.sessions[1].sets.forEach(s=>s.weight=20);
assert.equal(one(input).workComparison,null);
assert.equal(analyze(input).workoutFeedback.improved,0,'A heavier failed attempt does not establish more strength');
assert.equal(one(input).prHistory.some(r=>r.type==='estimated_strength'),false);
assert.equal(one(input).e1rmConfidence,'low');
input=data([workout(10,[10,9,8]),workout(11,[10,9,8]),...Array.from({length:7},(_,i)=>workout(12+i,[8],{status:'partial'}))]);
assert.equal(one(input).sessionsWithoutImprovement,1,'Partial workouts do not manufacture a plateau');
assert.equal(analyze(input).workoutFeedback.date,'2026-09-11');
input=data([workout(18,[10,9,8]),workout(19,[12,12,12])]);
input.sessions[1].sets.forEach(s=>s.techniqueValid=false);
assert.match(one(input).nextTarget.reason,/technique issue/,'Entire invalid latest occurrence still blocks progression');
input=data([workout(19,[10,9,8])]);
input.sessions[0].sets.push({...input.sessions[0].sets[0],id:'duplicate-slot'});
assert.equal(analyze(input).overall.validSets,3,'Duplicate slot cannot manufacture a fourth working set');
const active=workout(20,[12,12,12]);
const before=JSON.stringify(input);
assert.deepEqual(getWorkoutExerciseProgress(input,active,active.exercises[0]).nextTarget,one(input).nextTarget);
const alternate={id:'B',name:'Plan B',exerciseIds:[{exerciseId:'squat',targetSets:2,targetRepMin:5,targetRepMax:8}]};
input.plans.push(alternate);
const alternateAnalysis=analyze({...input,plans:[alternate]});
const exported=formatWorkoutAIExport(input,'2026-09-20',{planId:'B',active:{session:active}});
const exportedAnalysis=JSON.parse(exported.split('=== PROGRESS ANALYSIS JSON ===\n')[1].split('\n\n=== RAW HISTORY SUMMARY CSV ===')[0]);
assert.deepEqual(exportedAnalysis,alternateAnalysis,'Selected plan is preserved in the export');
const exportedActive=JSON.parse(exported.split('=== CURRENT WORKOUT TARGETS JSON ===\n')[1].split('\n\n=== PLANS CSV ===')[0]);
assert.deepEqual(exportedActive[0].target,getWorkoutExerciseProgress(input,active,active.exercises[0]).nextTarget);
input.plans.pop();
assert.equal(JSON.stringify(input),before,'No calculation/export mutates the recorded history');
input=data([]);
input.exercises[0]={...exercise,trackingType:'time'};
input.plans=[{...plan,exerciseIds:[{exerciseId:'squat',targetSets:3,targetDurationMin:30,targetDurationMax:60}]}];
assert.deepEqual(one(input).nextTarget.setTargets.map(s=>s.durationSeconds),[30,30,30],'Initial hold uses the lower planned bound');
console.log('PASS report truthfulness, comparable set totals, partial sessions, invalid attempts, single dumbbell, selected-plan and active-target export parity');
